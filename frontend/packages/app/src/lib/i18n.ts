export type MessageKey = keyof typeof en;

const catalogs: Record<Locale, Record<string, string>> = { en };

let activeLocale: Locale = "en";

export function setLocale(locale: Locale): void {
  activeLocale = locale;
}

/** True in a dev build (Vite's `import.meta.env.DEV`), without depending on Vite's types here. */
const DEV = (import.meta as unknown as { env?: { DEV?: boolean } }).env?.DEV ?? true;

const missingKeys = new Set<string>();

/** Keys `t()` was asked for that no catalog defines — handy in tests and the console. */
export function missingMessageKeys(): string[] {
  return [...missingKeys];
}

/**
 * Translate `key`, interpolating `{name}` placeholders from `vars`.
 * Unknown keys fall back to the key itself so nothing renders blank, and are logged once (in dev)
 * so a missing catalog entry shows up as a warning rather than as a raw key in the UI.
 */
/** Whether the text has Chinese, Japanese or Korean characters: a card in that language gets Chinese button labels. */
export function hasCjk(text: string | undefined): boolean {
  return /[\u3040-\u30ff\u3400-\u9fff\uac00-\ud7af]/.test(text ?? "");
}

/** The Start / Not now / Do it label for a card whose own text is `text`. */
export function cardLabel(kind: "start" | "notNow" | "doIt", text: string | undefined): string {
  if (hasCjk(text)) return { start: "开始", notNow: "以后再说", doIt: "去做" }[kind];
  return t({ start: "inspiration.begin", notNow: "ideas.notNow", doIt: "ideas.doIt" }[kind]);
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const catalog = catalogs[activeLocale] ?? en;
  let template = catalog[key] ?? (en as Record<string, string>)[key];
  if (template === undefined) {
    if (!missingKeys.has(key)) {
      missingKeys.add(key);
      if (DEV) console.warn(`[i18n] missing message key: "${key}"`);
    }
    template = key;
  }
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}
