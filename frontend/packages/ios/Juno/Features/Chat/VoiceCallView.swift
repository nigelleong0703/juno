import SwiftUI

/// The presentation of an in-app call. The call controller owns the session and passes only plain values: the call
/// state, a smoothed 0...1 audio level and the turns of this call.
struct VoiceCallView: View {
    struct Turn: Identifiable, Equatable {
        let id: String
        let isUser: Bool
        let text: String
        let isFinal: Bool
    }

    let agent: Agent?
    let state: VoiceCallState
    let level: Float
    let turns: [Turn]
    let muted: Bool
    let toggleMute: () -> Void
    let showText: () -> Void
    let end: () -> Void

    @Environment(\.accessibilityReduceMotion) private var reduceMotion
    @AppStorage("voiceCall.subtitles") private var subtitles = false
    @State private var entered = false

    /// The call is always dark, whatever the system appearance.
    private static let background = Color(red: 0.04, green: 0.04, blue: 0.05)
    private static let controlFill = Color(white: 0.16)
    private static let secondary = Color.white.opacity(0.6)

    var body: some View {
        VStack(spacing: 0) {
            header
                .padding(.horizontal, 24).padding(.top, 16)
                .opacity(entered ? 1 : 0)

            Spacer(minLength: 16)
            CallOrb(agent: agent, state: state, level: level, muted: muted)
                .scaleEffect(entered || reduceMotion ? 1 : 0.82)
                .opacity(entered ? 1 : 0)
            VStack(spacing: 14) {
                ThinkingDots(state: state)
                Text(status).text(.base)
                    .foregroundStyle(state.isFailed ? Theme.danger : Self.secondary)
                    .multilineTextAlignment(.center)
                    .contentTransition(.opacity)
                    .animation(.smooth(duration: 0.25), value: status)
            }
            .padding(.top, 8).padding(.horizontal, 32)
            .accessibilityElement(children: .combine)
            Spacer(minLength: 16)

            captions
                .frame(height: 132, alignment: .top)
                .opacity(entered ? 1 : 0)

            HStack(spacing: 28) {
                CallButton(symbol: muted ? "mic.slash.fill" : "mic.fill", label: muted ? "Unmute" : "Mute",
                           fill: muted ? .white : Self.controlFill, symbolColor: muted ? .black : .white, action: toggleMute)
                CallButton(symbol: "keyboard", label: "Text", fill: Self.controlFill, symbolColor: .white, action: showText)
                CallButton(symbol: "xmark", label: "End call", fill: Self.controlFill, symbolColor: Theme.danger, action: end)
            }
            .padding(.top, 12)
            .offset(y: entered || reduceMotion ? 0 : 56)
            .opacity(entered ? 1 : 0)

            Text("Content generated by AI").text(.xs).foregroundStyle(Color.white.opacity(0.35))
                .padding(.top, 20).padding(.bottom, 12)
                .opacity(entered ? 1 : 0)
        }
        .background(Self.background.ignoresSafeArea())
        .environment(\.colorScheme, .dark)
        .task {
            guard !entered else { return }
            withAnimation(reduceMotion ? .easeOut(duration: 0.2) : .spring(response: 0.6, dampingFraction: 0.82)) { entered = true }
        }
    }

    private var header: some View {
        HStack {
            Text(agent?.name ?? "Agent").text(.sm, .medium).foregroundStyle(Self.secondary)
            Spacer()
            Button { subtitles.toggle() } label: {
                Image(systemName: subtitles ? "captions.bubble.fill" : "captions.bubble")
                    .font(.system(size: 20, weight: .regular))
                    .foregroundStyle(subtitles ? Color.white : Self.secondary)
                    .frame(width: 44, height: 44)
                    .contentShape(Rectangle())
            }
            .buttonStyle(.plain)
            .accessibilityLabel(subtitles ? "Hide subtitles" : "Show subtitles")
        }
    }

    /// What the call is doing, in a sentence.
    private var status: String {
        switch state {
        case .listening: muted ? "Microphone is off" : "You can start talking"
        case .speaking: "\(agent?.name ?? "Agent") is speaking"
        default: state.label
        }
    }

    /// The latest turn or two, not the whole transcript.
    @ViewBuilder private var captions: some View {
        if subtitles {
            VStack(spacing: 10) {
                ForEach(turns.suffix(2)) { turn in
                    Text(turn.text).text(.base)
                        .foregroundStyle(turn.isUser ? Self.secondary : Color.white)
                        .opacity(turn.isFinal ? 1 : 0.55)
                        .multilineTextAlignment(.center)
                        .lineLimit(3)
                        .frame(maxWidth: .infinity)
                        .animation(.easeOut(duration: 0.3), value: turn.isFinal)
                        .transition(reduceMotion ? .opacity : .opacity.combined(with: .offset(y: 12)))
                }
            }
            .padding(.horizontal, 32)
            .animation(.smooth(duration: 0.3), value: turns.map(\.id))
            .transition(.opacity)
        }
    }
}

private extension VoiceCallState {
    var isFailed: Bool { if case .failed = self { true } else { false } }
}

/// Round dark-grey call button with a small caption underneath.
private struct CallButton: View {
    let symbol: String
    let label: String
    let fill: Color
    let symbolColor: Color
    let action: () -> Void

    var body: some View {
        Button(action: action) {
            Image(systemName: symbol).font(.system(size: 30, weight: .medium))
                .foregroundStyle(symbolColor)
                .frame(width: 76, height: 76)
                .background(Circle().fill(fill))
                .contentShape(Circle())
        }
        .buttonStyle(.plain)
        .accessibilityLabel(label)
    }
}

/// Three dots that ripple while the agent works (connecting, thinking), glow with the level while talking, and sit
/// still otherwise. Static with Reduce Motion.
private struct ThinkingDots: View {
    let state: VoiceCallState
    @Environment(\.accessibilityReduceMotion) private var reduceMotion

    var body: some View {
        TimelineView(.animation(minimumInterval: 1 / 30, paused: reduceMotion || !animates)) { timeline in
            let time = timeline.date.timeIntervalSinceReferenceDate
            HStack(spacing: 10) {
                ForEach(0..<3, id: \.self) { index in
                    let wave = reduceMotion || !animates ? 0.5 : sin(time * speed - Double(index) * 0.9) * 0.5 + 0.5
                    Circle().fill(Color.white)
                        .frame(width: 8, height: 8)
                        .scaleEffect(0.8 + 0.4 * wave)
                        .opacity(0.35 + 0.5 * wave)
                }
            }
        }
        .accessibilityHidden(true)
    }

    private var animates: Bool {
        switch state {
        case .connecting, .thinking, .speaking, .listening: true
        case .ended, .failed: false
        }
    }

    private var speed: Double { state == .connecting ? 7 : state == .thinking ? 4.5 : 2.5 }
}

/// A soft pink/lavender fluid orb with a dark glow around it. It follows your level while listening and the agent's
/// while speaking, breathes slowly while thinking and pulses quicker while connecting. With Reduce Motion it is
/// still and only changes opacity.
private struct CallOrb: View {
    let agent: Agent?
    let state: VoiceCallState
    let level: Float
    let muted: Bool
    @Environment(\.accessibilityReduceMotion) private var reduceMotion

    private let size: CGFloat = 270

    var body: some View {
        let tint = agentTint(agent)
        let pink = Color(red: 1.0, green: 0.62, blue: 0.80).mix(with: tint, by: 0.2)
        let lavender = Color(red: 0.72, green: 0.64, blue: 1.0).mix(with: tint, by: 0.2)
        let white = Color(red: 0.98, green: 0.94, blue: 1.0)
        TimelineView(.animation(minimumInterval: 1 / 30, paused: reduceMotion)) { timeline in
            let time = reduceMotion ? 0 : timeline.date.timeIntervalSinceReferenceDate
            let breath = CGFloat(reduceMotion ? 0.5 : sin(time * 2 * .pi / period) * 0.5 + 0.5)
            let amount = CGFloat(state.followsLevel ? level : 0)
            ZStack {
                Circle()
                    .fill(RadialGradient(colors: [pink.opacity(0.45), lavender.opacity(0.18), .clear],
                                         center: .center, startRadius: size * 0.3, endRadius: size * 0.95))
                    .frame(width: size * 1.9, height: size * 1.9)
                    .opacity(glowOpacity(amount: amount, breath: breath))
                    .scaleEffect(1 + 0.12 * amount + 0.05 * breathing(breath))
                MeshGradient(width: 3, height: 3, points: points(time), colors: [
                    white, pink, lavender,
                    pink, white, pink,
                    lavender, pink, white
                ])
                .frame(width: size, height: size)
                .clipShape(Circle())
                .overlay(Circle().strokeBorder(Color.white.opacity(0.25), lineWidth: 1))
                // The agent's own character sits in the orb, animating with the agent's live status (working while a run is on).
                .overlay(AvatarView(agent: agent, size: size * 0.5).scaleEffect(1 + 0.08 * amount))
                .scaleEffect(1 + 0.06 * amount + 0.03 * breathing(breath))
                .opacity(muted && state == .listening ? 0.45 : 1)
            }
            .frame(width: size * 1.5, height: size * 1.5)
        }
        .animation(.smooth(duration: 0.5), value: state)
        .animation(.linear(duration: 0.08), value: level)
        .animation(.smooth(duration: 0.3), value: muted)
        .accessibilityHidden(true)
    }

    /// Interior mesh points drift slowly so the colours flow; corners and edges stay put.
    private func points(_ time: Double) -> [SIMD2<Float>] {
        func drift(_ speed: Double, _ phase: Double) -> Float { Float(sin(time * speed + phase) * 0.08) }
        return [
            [0, 0], [0.5 + drift(0.31, 0), 0], [1, 0],
            [0, 0.5 + drift(0.27, 1)], [0.5 + drift(0.23, 2), 0.5 + drift(0.29, 3)], [1, 0.5 + drift(0.33, 4)],
            [0, 1], [0.5 + drift(0.25, 5), 1], [1, 1]
        ]
    }

    /// Seconds per breath: thinking is a slow pulse, connecting a little quicker and shallower.
    private var period: Double { state == .thinking ? 2.8 : 1.8 }

    /// Only connecting and thinking breathe; level states move with the audio.
    private func breathing(_ breath: CGFloat) -> CGFloat {
        switch state {
        case .thinking: breath
        case .connecting: breath * 0.6
        default: 0
        }
    }

    private func glowOpacity(amount: CGFloat, breath: CGFloat) -> Double {
        switch state {
        case .listening: muted ? 0.15 : 0.5 + 0.5 * Double(amount)
        case .speaking: 0.6 + 0.4 * Double(amount)
        case .thinking: 0.5 + 0.3 * Double(breath)
        case .connecting: 0.3 + 0.3 * Double(breath)
        case .ended, .failed: 0.1
        }
    }
}

