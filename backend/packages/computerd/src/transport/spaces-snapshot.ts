/**
 * The snapshot of a published Space, read on its computer (BACKEND 5.12, option B): the built pages (`dist/` of an app,
 * `public/` of a static one) and the rows of `data/app.db`, as one JSON document on stdout. The program is ours and fixed; the
 * slug is the only input, checked here and again inside the program. Read-only: nothing on the computer is written.
 */
const PROGRAM = [
  'import base64, json, os, re, sqlite3, sys',
  'slug = sys.argv[1]',
  'if not re.fullmatch(r"[a-z0-9][a-z0-9-]{0,40}", slug):',
  '    sys.exit("bad slug")',
  'base = os.path.join(os.environ.get("JUNO_SPACES_ROOT", "/workspace/spaces"), slug)',
  'MAX_BYTES = 10 * 1024 * 1024',
  'MAX_FILES = 500',
  'MAX_ROWS = 10000',
  'def fail(message):',
  '    sys.stderr.write(message + "\\n")',
  '    sys.exit(1)',
  'if os.path.isfile(os.path.join(base, "dist", "index.html")):',
  '    root = "dist"',
  'elif os.path.isfile(os.path.join(base, "public", "index.html")):',
  '    root = "public"',
  'else:',
  '    fail("no built index.html: run spaces_tool.py build " + slug)',
  '# server code: every server file (root-level .ts/.js) must be the app template\'s own, and no other folder or file may sit at the root',
  'template = os.path.join(os.environ.get("JUNO_SPACES_TEMPLATES", "/opt/juno/skills/spaces/templates"), "app" if root == "dist" else "static")',
  'if not os.path.isdir(template):',
  '    fail("the spaces template is not on this computer")',
  'CODE = (".ts", ".js", ".mjs", ".cjs")',
  'NOT_SERVER = ("schema.ts", "drizzle.config.ts", "vite.config.ts")',
  'KNOWN_DIRS = ("dist", "public", "data", "migrations", "src", "node_modules")',
  'def same_file(a, b):',
  '    if not os.path.isfile(b):',
  '        return False',
  '    with open(a, "rb") as x, open(b, "rb") as y:',
  '        return x.read() == y.read()',
  'server = []',
  'for name in sorted(os.listdir(base)):',
  '    if name.startswith("."):',
  '        continue',
  '    full = os.path.join(base, name)',
  '    if os.path.isdir(full):',
  '        if name not in KNOWN_DIRS:',
  '            server.append(name + "/")',
  '    elif name.endswith(CODE) and name not in NOT_SERVER and not same_file(full, os.path.join(template, name)):',
  '        server.append(name)',
  'for name in sorted(os.listdir(template)):',
  '    if name.endswith(CODE) and name not in NOT_SERVER and not os.path.exists(os.path.join(base, name)):',
  '        server.append(name)',
  'top = os.path.join(base, root)',
  'files = []',
  'total = 0',
  'for dirpath, dirnames, filenames in os.walk(top):',
  '    dirnames[:] = [d for d in dirnames if not d.startswith(".")]',
  '    for name in filenames:',
  '        full = os.path.join(dirpath, name)',
  '        if name.startswith(".") or os.path.islink(full) or not os.path.isfile(full):',
  '            continue',
  '        total += os.path.getsize(full)',
  '        if total > MAX_BYTES:',
  '            fail("the pages are larger than 10 MiB")',
  '        if len(files) >= MAX_FILES:',
  '            fail("the Space has more than 500 files")',
  '        with open(full, "rb") as handle:',
  '            data = base64.b64encode(handle.read()).decode("ascii")',
  '        files.append({"path": os.path.relpath(full, top).replace(os.sep, "/"), "base64": data})',
  'tables = {}',
  'db_path = os.path.join(base, "data", "app.db")',
  'if os.path.isfile(db_path):',
  '    connection = sqlite3.connect("file:" + db_path + "?mode=ro", uri=True)',
  '    try:',
  '        names = [row[0] for row in connection.execute("SELECT name FROM sqlite_master WHERE type = \'table\' AND name NOT LIKE \'sqlite_%\' AND name NOT LIKE \'__drizzle%\' ORDER BY name")]',
  '        rows_total = 0',
  '        for name in names:',
  '            if not re.fullmatch(r"[a-z][a-z0-9_]{0,62}", name):',
  '                fail("table name not hostable: " + name)',
  '            cursor = connection.execute(\'SELECT * FROM "\' + name + \'"\')',
  '            columns = [column[0] for column in cursor.description]',
  '            rows = []',
  '            for values in cursor:',
  '                rows_total += 1',
  '                if rows_total > MAX_ROWS:',
  '                    fail("the data has more than 10000 rows")',
  '                rows.append({column: (None if isinstance(value, bytes) else value) for column, value in zip(columns, values)})',
  '            tables[name] = rows',
  '    finally:',
  '        connection.close()',
  'sys.stdout.write(json.dumps({"root": root, "files": files, "tables": tables, "serverCode": server}))',
].join('\n');

/** The shell command that runs the program on the slug's folder (single-quoted for the POSIX shell, the slug checked again inside). */
export function snapshotCommand(slug: string): string {
  return `python3 -c ${shellQuote(PROGRAM)} ${shellQuote(slug)}`;
}

function shellQuote(value: string): string {
  return `'${value.split("'").join(`'"'"'`)}'`;
}
